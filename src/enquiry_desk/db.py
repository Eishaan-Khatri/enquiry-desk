"""The desk's own records: usage, leads, notes, slots, jobs. SQLite or PostgreSQL.

`Database("var/desk.db")` is SQLite: one file, nothing to install, right for one process on
one machine. `Database("postgresql://...")` is PostgreSQL: a server that many processes can
write to at once, which a deployment with more than one worker needs.

Every other module writes its SQL once, in the dialect SQLite accepts. The PostgreSQL class
translates the few differences on the way in (see `_for_postgres`) and installs a handful of
functions so that the same report files run unchanged (see `POSTGRES_COMPAT`).
"""

from __future__ import annotations

import os
import re
import sqlite3
import threading
import uuid
from pathlib import Path

POSTGRES = ("postgresql://", "postgres://")


class Database:
    def __new__(cls, path: Path | str = ":memory:"):
        target = str(path)
        # Tests ask for an in-memory database. With this variable set they get a fresh, empty
        # PostgreSQL schema instead, so the whole test suite can be run against PostgreSQL.
        test_url = os.environ.get("DESK_TEST_DATABASE_URL")
        if target == ":memory:" and test_url:
            return PostgresDatabase(test_url, schema="t_" + uuid.uuid4().hex[:16])
        if target.startswith(POSTGRES):
            return PostgresDatabase(target)
        return super().__new__(cls)

    def __init__(self, path: Path | str = ":memory:"):
        if str(path) != ":memory:":
            Path(path).parent.mkdir(parents=True, exist_ok=True)
        # isolation_level=None is autocommit: each statement is its own transaction.
        # A single connection guarded by a lock. Each statement takes well under a millisecond
        # at this size, so the calls are made straight from async code.
        self._conn = sqlite3.connect(str(path), check_same_thread=False, isolation_level=None)
        self._conn.row_factory = sqlite3.Row
        self._lock = threading.Lock()

    def script(self, sql: str) -> None:
        with self._lock:
            self._conn.executescript(sql)

    def query(self, sql: str, params: tuple | dict = ()) -> list:
        with self._lock:
            return self._conn.execute(sql, params).fetchall()

    def run(self, sql: str, params: tuple = ()) -> int:
        """Run a write. Returns how many rows it changed."""
        with self._lock:
            return self._conn.execute(sql, params).rowcount

    def close(self) -> None:
        with self._lock:
            self._conn.close()


# Functions and one aggregate that SQLite has and PostgreSQL does not, written in SQL, so the
# report files need no second version. Each is a single statement with no semicolon inside.
POSTGRES_COMPAT = """
CREATE OR REPLACE FUNCTION date(double precision, text) RETURNS text
    AS 'SELECT to_char(to_timestamp($1) AT TIME ZONE ''UTC'', ''YYYY-MM-DD'')' LANGUAGE SQL IMMUTABLE;
CREATE OR REPLACE FUNCTION date(text, text) RETURNS text
    AS 'SELECT to_char($1::date + replace($2, '' day'', '''')::integer, ''YYYY-MM-DD'')' LANGUAGE SQL IMMUTABLE;
CREATE OR REPLACE FUNCTION datetime(double precision, text) RETURNS text
    AS 'SELECT to_char(to_timestamp($1) AT TIME ZONE ''UTC'', ''YYYY-MM-DD HH24:MI:SS'')' LANGUAGE SQL IMMUTABLE;
CREATE OR REPLACE FUNCTION strftime(text, double precision, text) RETURNS text
    AS 'SELECT to_char(to_timestamp($2) AT TIME ZONE ''UTC'', ''YYYY-"W"WW'')' LANGUAGE SQL IMMUTABLE;
CREATE OR REPLACE FUNCTION round(double precision, integer) RETURNS double precision
    AS 'SELECT round($1::numeric, $2)::double precision' LANGUAGE SQL IMMUTABLE;
CREATE OR REPLACE FUNCTION desk_count_true(bigint, boolean) RETURNS bigint
    AS 'SELECT $1 + CASE WHEN $2 THEN 1 ELSE 0 END' LANGUAGE SQL IMMUTABLE
"""


def _for_postgres(sql: str, has_params: bool = True) -> str:
    """Rewrite one SQLite statement so PostgreSQL accepts it. Five differences, in order."""
    sql = re.sub(r"--[^\n]*", "", sql)  # comments first: they may hold '?' or ':' that are not parameters
    if has_params:
        # The driver reads % as the start of a parameter, so a literal one (LIKE, a date
        # format) is doubled. Without parameters the driver leaves the text alone.
        sql = sql.replace("%", "%%")
    # SQLite numbers the rows of an INTEGER PRIMARY KEY by itself. PostgreSQL has to be told.
    sql = re.sub(r"\bINTEGER PRIMARY KEY\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql)
    # REAL is 8 bytes in SQLite and 4 in PostgreSQL. Four bytes cannot hold a timestamp to the second.
    sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)
    sql = sql.replace("?", "%s")  # positional parameters
    return re.sub(r"(?<![:\w]):([a-z_]+)\b", r"%(\1)s", sql)  # named parameters, but not '::' casts


class PostgresDatabase:
    """The same four methods as `Database`, on PostgreSQL."""

    def __init__(self, url: str, schema: str | None = None):
        import psycopg
        from psycopg.rows import dict_row
        from psycopg.types.numeric import FloatLoader

        # autocommit matches the SQLite class: each statement is its own transaction.
        self._conn = psycopg.connect(url, autocommit=True, row_factory=dict_row)
        # NUMERIC would arrive as Decimal. Everything else in the desk works in floats.
        self._conn.adapters.register_loader("numeric", FloatLoader)
        self._lock = threading.Lock()
        if schema:
            self._conn.execute(f'CREATE SCHEMA "{schema}"')
            self._conn.execute(f'SET search_path TO "{schema}", public')
        self.script(POSTGRES_COMPAT)
        # SUM(condition) counts the rows where the condition holds. SQLite allows it because
        # true is 1. PostgreSQL has no SUM over booleans, so one is defined.
        exists = self._conn.execute(
            "SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace"
            " WHERE p.proname = 'sum' AND n.nspname = current_schema() AND p.prokind = 'a'"
        ).fetchone()
        if not exists:
            self._conn.execute("CREATE AGGREGATE sum(boolean) (SFUNC = desk_count_true, STYPE = bigint, INITCOND = '0')")

    def script(self, sql: str) -> None:
        with self._lock:
            for statement in _for_postgres(sql, has_params=False).split(";"):
                if statement.strip():
                    self._conn.execute(statement)

    def query(self, sql: str, params: tuple | dict = ()) -> list:
        with self._lock:
            cursor = self._conn.execute(_for_postgres(sql, bool(params)), params or None)
            return cursor.fetchall() if cursor.description else []

    def run(self, sql: str, params: tuple = ()) -> int:
        with self._lock:
            return self._conn.execute(_for_postgres(sql, bool(params)), params or None).rowcount

    def close(self) -> None:
        with self._lock:
            self._conn.close()
